def render(name: str, **kwargs: object) -> str:
    if name not in REGISTRY:
        raise KeyError(f"Unknown prompt: {name}")
    return Template(REGISTRY[name]).substitute(**kwargs)


def prompt_meta() -> dict[str, str]:
    return {"version": settings.PROMPT_VERSION, "count": str(len(REGISTRY))}
